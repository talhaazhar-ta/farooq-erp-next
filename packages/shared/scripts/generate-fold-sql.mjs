// Generates the SQL of `fold_search(text)` and the `search_join` overloads (the tail of
// packages/db/migrations/0004_s4_search_receipt.sql) from the SAME definitions the JavaScript `foldSearch` uses
// (packages/shared/src/fold.ts), so the two cannot drift apart by hand.
//
//   pnpm --filter @farooq/shared build && node packages/shared/scripts/generate-fold-sql.mjs > fold_search.sql
//
// Three tiers, all exactly equal to the JS `foldSearch` (the parity test covers every code point through each of them):
//   1. pure ASCII (octet_length = char_length)          lower-case A-Z, everything outside [a-z0-9] becomes a space   (~2 µs)
//   2. ASCII + the Arabic block (Urdu, the common case)  no lower-casing beyond ASCII is possible there, so the 1487-pair
//                                                        lower-case table is skipped; a short non-word range list
//   3. anything else (accents, Greek, CJK ...)           the full table and the full range list                          (~130 µs)
//
// Why generated: `[^\p{L}\p{N}]` in JavaScript follows Unicode; Postgres' `[[:alpha:]]` follows the database locale and,
// in the C locale the embedded test cluster uses, treats every non-ASCII letter (all of Urdu) as punctuation. So the SQL
// spells the classification out as explicit code-point ranges instead. The parity test
// (apps/api/test/fold-search-parity.test.ts) feeds every code point through both and must stay green; if a Node upgrade
// ships a newer Unicode table it will go red, and re-running this script (into a NEW migration) is the fix.
import { DIGIT_MAP, LETTER_MAP } from "../dist/fold.js";

const MAX = 0x10ffff;
const isWord = (cp) => /[\p{L}\p{N}]/u.test(String.fromCodePoint(cp));
const isSurrogate = (cp) => cp >= 0xd800 && cp <= 0xdfff;
// a regex-escape Postgres understands inside a bracket expression: \uXXXX or \UXXXXXXXX (the backslash is literal SQL text)
const esc = (cp) => (cp > 0xffff ? "\\U" + cp.toString(16).padStart(8, "0") : "\\u" + cp.toString(16).padStart(4, "0"));
const bracket = (ranges) => ranges.map(([a, b]) => (a === b ? esc(a) : esc(a) + "-" + esc(b))).join("");

// 1. per-character lower-casing: every code point whose lower-case form is one different code point.
const lowerFrom = [];
const lowerTo = [];
const multi = [];
for (let cp = 1; cp <= MAX; cp++) {
  if (isSurrogate(cp)) continue;
  const c = String.fromCodePoint(cp);
  const l = c.toLowerCase();
  if (l === c) continue;
  if ([...l].length === 1) {
    lowerFrom.push(c);
    lowerTo.push(l);
  } else multi.push([c, l]);
}
if (multi.length !== 1 || multi[0][0] !== "İ") throw new Error(`Unexpected multi-character lower-casing: ${JSON.stringify(multi)}`);

// 2. the code points that are neither a letter nor a number, as compact ranges (NUL and surrogates cannot occur in text).
const ranges = [];
let start = null;
for (let cp = 1; cp <= MAX + 1; cp++) {
  const nonWord = cp <= MAX && !isSurrogate(cp) && !isWord(cp);
  if (nonWord && start === null) start = cp;
  if (!nonWord && start !== null) {
    ranges.push([start, cp - 1]);
    start = null;
  }
}

// tier 2: the same ranges restricted to ASCII + the Arabic block + the zero-width marks
const FAST = [[0x01, 0x7f], [0x0600, 0x06ff], [0x200c, 0x200f]];
const fastRanges = [];
for (const [a, b] of ranges) {
  for (const [fa, fb] of FAST) {
    const lo = Math.max(a, fa);
    const hi = Math.min(b, fb);
    if (lo <= hi) fastRanges.push([lo, hi]);
  }
}

const q = (s) => `'${s.replace(/'/g, "''")}'`;
const UPPER = "ABCDEFGHIJKLMNOPQRSTUVWXYZ";
const LOWER = UPPER.toLowerCase();
const digitFrom = Object.keys(DIGIT_MAP).join("");
const digitTo = Object.values(DIGIT_MAP).join("");
const letterFrom = Object.keys(LETTER_MAP).join("");
const letterTo = Object.values(LETTER_MAP).join("");
const stripClass = `[${bracket([[0x064b, 0x0652], [0x0670, 0x0670], [0x0640, 0x0640], [0x200c, 0x200f]])}]`;
const fastText = `[^${bracket(FAST)}]`;

process.stdout.write(`-- GENERATED by packages/shared/scripts/generate-fold-sql.mjs — do not edit by hand (see that file).
-- fold_search(text) = foldSearch() of packages/shared/src/fold.ts: lower-case (per character) -> strip harakat /
-- tatweel / zero-width marks -> fold digits -> fold letter variants -> every run of non-letter, non-digit becomes one
-- space -> trim. NULL folds to ''. General tier: ${lowerFrom.length} lower-case pairs, ${ranges.length} non-word ranges;
-- Arabic tier: ${fastRanges.length} non-word ranges. ASCII lower-casing is spelled out (never lower()) so the result
-- cannot depend on the database locale.
CREATE FUNCTION "fold_search"(input text) RETURNS text
LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $fold$
SELECT CASE
  WHEN input IS NULL OR input = '' THEN ''
  WHEN octet_length(input) = char_length(input) THEN
    btrim(regexp_replace(translate(input, ${q(UPPER)}, ${q(LOWER)}), '[^a-z0-9]+', ' ', 'g'), ' ')
  WHEN input !~ '${fastText}' THEN
    btrim(
      regexp_replace(
        translate(
          translate(
            regexp_replace(translate(input, ${q(UPPER)}, ${q(LOWER)}), '${stripClass}', '', 'g'),
            ${q(digitFrom)}, ${q(digitTo)}),
          ${q(letterFrom)}, ${q(letterTo)}),
        '[${bracket(fastRanges)}]+', ' ', 'g'),
      ' ')
  ELSE
    btrim(
      regexp_replace(
        translate(
          translate(
            regexp_replace(
              replace(
                translate(input, ${q(lowerFrom.join(""))}, ${q(lowerTo.join(""))}),
                'İ', 'i' || chr(775)),
              '${stripClass}', '', 'g'),
            ${q(digitFrom)}, ${q(digitTo)}),
          ${q(letterFrom)}, ${q(letterTo)}),
        '[${bracket(ranges)}]+', ' ', 'g'),
      ' ')
END
$fold$;
`);

// search_join: fixed-arity overloads. The planner inlines a plain SQL function of this shape, and a VARIADIC array plus
// unnest costs more than the folds it joins. Each part is folded, empties are dropped, the rest are joined by chr(1).
for (const n of [2, 3, 4, 5, 7, 8]) {
  const params = Array.from({ length: n }, (_, i) => `p${i + 1} text`).join(", ");
  const parts = Array.from({ length: n }, (_, i) => `NULLIF(fold_search(p${i + 1}), '')`).join(", ");
  process.stdout.write(`--> statement-breakpoint
CREATE FUNCTION "search_join"(${params}) RETURNS text
LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $fn$
SELECT concat_ws(chr(1), ${parts})
$fn$;
`);
}
